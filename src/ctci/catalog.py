CHAPTERS: Dict[str, Dict[str, object]] = {chapter["id"]: chapter for chapter in _CHAPTER_DATA}
PROBLEMS: Dict[Tuple[str, int], Problem] = {
    (problem.chapter, problem.number): problem
    for chapter in _CHAPTER_DATA
    for problem in chapter["problems"]
}


def iter_chapters() -> Iterable[Dict[str, object]]:
    """Iterate over chapter metadata in book order."""

    return tuple(_CHAPTER_DATA)


def iter_problems() -> Iterable[Problem]:
    """Iterate over every problem in book order."""

    return tuple(PROBLEMS.values())


def get_problem(chapter: str, number: int) -> Problem:
    """Fetch problem metadata by chapter identifier and number."""

    try:
        return PROBLEMS[(chapter, number)]
    except KeyError as exc:  # pragma: no cover - defensive branch
        raise KeyError(f"Unknown problem: {chapter} #{number}") from exc
