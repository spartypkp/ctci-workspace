"""Problem catalog for Cracking the Coding Interview practice workspace."""
from __future__ import annotations

from dataclasses import dataclass
from typing import Dict, Iterable, List, Tuple


@dataclass(frozen=True)
class Problem:
    """Metadata that describes an individual CTCI problem."""

    chapter: str
    number: int
    slug: str
    title: str
    summary: str
    tags: Tuple[str, ...] = ()

    @property
    def code_path(self) -> str:
        """Return the expected module path for the problem implementation."""
        return f"ctci.chapters.{self.chapter}.p{self.number:02d}_{self.slug}"

    @property
    def note_filename(self) -> str:
        """Return the suggested markdown filename for journaling."""
        return f"{self.chapter}_p{self.number:02d}_{self.slug}.md"


def _chapter(
    identifier: str,
    title: str,
    problems: Iterable[Dict[str, object]],
) -> Dict[str, object]:
    """Helper to build a chapter definition."""

    return {
        "id": identifier,
        "title": title,
        "problems": [Problem(chapter=identifier, **problem) for problem in problems],
    }


